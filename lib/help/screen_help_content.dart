/// قسم قابل للطي: مقدمة اختيارية، نقاط، وأقسام فرعية.
class HelpSection {
  final String title;
  final String? intro;
  final List<String> points;
  final List<HelpSection> children;

  const HelpSection(this.title, {this.intro, this.points = const [], this.children = const []});
}

/// شرح شاشة واحدة: ملخص، نقاط سريعة (للشاشات البسيطة)، وأقسام مفصّلة.
class ScreenHelp {
  final String title;
  final String summary;
  final List<String> points;
  final List<HelpSection> sections;

  const ScreenHelp({required this.title, required this.summary, this.points = const [], this.sections = const []});
}

/// شرح الشاشة الحالية، أو null إن لم يُكتب لها شرح.
ScreenHelp? screenHelpFor(String? page) => page == null ? null : screenHelp[page];

